CREATE TABLE ACCOUNT
(
    ACNO NUMBER PRIMARY KEY,
    CNAME VARCHAR2(50),
    BNAME VARCHAR2(50),
    BALANCE NUMBER(10,2)
);

CREATE OR REPLACE FUNCTION GET_BALANCE
(
    p_acno NUMBER
)
RETURN NUMBER
IS
    bal NUMBER;
BEGIN
    SELECT BALANCE
    INTO bal
    FROM ACCOUNT
    WHERE ACNO=p_acno;

    RETURN bal;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN 0;
END;
/

DECLARE
    b NUMBER;
BEGIN
    b:=GET_BALANCE(&ACNO);

    dbms_output.put_line('Balance:'||b);
END;
/
